const COUNTRIES = COUNTRY_DATA.map(([name, demonym, aliases]) => ({
  name,
  demonym,
  aliases: aliases ? aliases.split(',').map((s) => s.trim()) : [],
}));

/**
 * Map an old free-text "nationality" value to a country name, or return it unchanged.
 * Only exact (case-insensitive) matches on a name, nationality or alias are converted;
 * a nationality shared by two countries (e.g. "Dominican") is left as it was.
 */
function countryFromLegacyValue(value) {
  const v = String(value || '').trim();
  if (!v) return v;
  const key = v.toLowerCase();
  const byName = COUNTRIES.find((c) => c.name.toLowerCase() === key);
  if (byName) return byName.name;
  const matches = COUNTRIES.filter((c) =>
    c.demonym.toLowerCase() === key || c.aliases.some((a) => a.toLowerCase() === key));
  // old picker values like "Congolese (DR Congo)" / "Basotho (Lesotho)"
  const paren = /^(.+?)\s*\((.+)\)$/.exec(v);
  if (!matches.length && paren) {
    const isCountry = (name) => COUNTRIES.some((c) => c.name === name);
    const inner = countryFromLegacyValue(paren[2]);
    if (isCountry(inner)) return inner;
    const outer = countryFromLegacyValue(paren[1]);
    return isCountry(outer) ? outer : v;
  }
  return matches.length === 1 ? matches[0].name : v;
}

